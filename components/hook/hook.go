// Package hook provides generic, concurrent-safe event hooks chained middleware-style | 提供泛型、并发安全、中间件式串联的事件钩子.
//
// # Notes | 说明
//
// Handlers run synchronously inside Trigger, in the caller's goroutine,
// ordered by Priority (stable sort). Each handler must call event.Next() to
// continue the chain; the first failing Next aborts it and its error bubbles
// up to Trigger. Bind/Unbind take a lock while Trigger and Length are
// lock-free: they read an immutable copy-on-write snapshot, so a running
// Trigger is never affected by a concurrent Bind or Unbind. The zero value is
// ready to use and must not be copied after first use.
// Handler 在 Trigger 内同步执行（调用方 goroutine），按 Priority 稳定排序。
// 每个 handler 必须调用 event.Next() 继续链条；首个失败的 Next 中止链条，
// 错误冒泡给 Trigger。Bind/Unbind 加锁，Trigger/Length 无锁：读的是写时复制
// 的不可变快照，运行中的 Trigger 不受并发 Bind/Unbind 影响。零值可用，
// 首次使用后不可复制。
//
// # Features | 功能
//
// - Generic Hook[T] over events embedding [Event] | 泛型 Hook[T]，事件内嵌 [Event]
// - Id-based Bind/BindFunc/Unbind/UnbindAll | 按 id 绑定与解绑
// - Re-entrant Trigger on the same event | 同一事件可重入 Trigger
// - [NewTaggedHook] filters handlers by event tags | [NewTaggedHook] 按事件标签过滤
//
// # Example | 示例
//
//	type OrderEvent struct {
//		hook.Event
//		OrderID string
//	}
//	h := hook.Hook[*OrderEvent]{}
//	h.BindFunc(func(e *OrderEvent) error { fmt.Println(e.OrderID); return e.Next() })
//	err := h.Trigger(&OrderEvent{OrderID: "o-1"})
package hook

import (
	"cmp"
	"slices"
	"strconv"
	"sync"
	"sync/atomic"
)

const errNilHandler = "hook: the handler and its Func must be non-nil"

// Handler defines a single Hook handler.
// Multiple handlers can share the same id.
// If Id is not explicitly set it will be autogenerated by Hook.Add and Hook.AddHandler.
// Handler 定义单个 Hook 处理器。多个处理器可共用同一 id；
// 未显式设置 Id 时由 Hook.Add / Hook.AddHandler 自动生成。
type Handler[T Resolver] struct {
	// Func defines the handler function to execute.
	//
	// Note that users need to call e.Next() in order to proceed with
	// the execution of the hook chain.
	// Func 定义要执行的处理函数。注意必须调用 e.Next() 才能继续执行钩子链。
	Func func(T) error

	// Id is the unique identifier of the handler.
	//
	// It could be used later to remove the handler from a hook via [Hook.Unbind].
	//
	// If missing, an autogenerated value will be assigned when adding
	// the handler to a hook.
	// Id 是处理器的唯一标识，之后可通过 [Hook.Unbind] 移除；
	// 缺省时在加入钩子时自动赋值。
	Id string

	// Priority allows changing the default exec priority of the handler within a hook.
	//
	// If 0, the handler will be executed in the same order it was registered.
	// Priority 允许调整处理器在钩子内的默认执行优先级；
	// 为 0 时按注册顺序执行。
	Priority int
}

// Hook defines a generic concurrent safe structure for managing event hooks.
//
// The zero value is ready to use. It must not be copied after first use.
//
// When using custom event it must embed the base [hook.Event].
//
// Example:
//
//	type CustomEvent struct {
//		hook.Event
//		SomeField int
//	}
//
//	h := Hook[*CustomEvent]{}
//
//	h.BindFunc(func(e *CustomEvent) error {
//		println(e.SomeField)
//
//		return e.Next()
//	})
//
//	h.Trigger(&CustomEvent{ SomeField: 123 })
//
// Concurrency: Bind/Unbind take a lock, while Trigger and Length are
// lock-free (they read an immutable snapshot of the handlers). A Trigger
// that is already running is never affected by a concurrent Bind or Unbind.
// Hook 定义管理事件钩子的泛型并发安全结构。零值即可用，首次使用后不可复制。
// 自定义事件必须内嵌基础 [hook.Event]。
//
// 并发性：Bind/Unbind 加锁，Trigger 与 Length 无锁（读处理器的不可变快照）；
// 已在运行的 Trigger 不受并发 Bind/Unbind 影响。
type Hook[T Resolver] struct {
	mu       sync.Mutex    // serializes the writers (Bind, Unbind, UnbindAll) | 串行化写方（Bind、Unbind、UnbindAll）
	handlers []*Handler[T] // private copies of the bound handlers; guarded by mu | 已绑处理器的私有副本；由 mu 保护

	// chain is an immutable snapshot of the handlers' funcs,
	// republished (copy-on-write) after every change of the handlers.
	// chain 是处理函数的不可变快照，handlers 每次变更后重新发布（写时复制）。
	chain atomic.Pointer[[]func(T) error]
}

// Bind registers the provided handler to the current hooks queue.
//
// If handler.Id is empty it is updated with autogenerated value.
//
// If a handler from the current hook list has Id matching handler.Id
// then the old handler is replaced with the new one.
//
// The hook keeps its own copy of the handler, so changing the passed
// struct after Bind has no effect on the hook (call Bind again with the
// same Id to update it).
//
// It panics if handler or handler.Func is nil.
// Bind 把给定处理器注册到当前钩子队列。handler.Id 为空时自动生成并回填；
// 已有同 Id 处理器时以新处理器替换旧处理器。钩子保存处理器的副本，
// Bind 之后修改传入结构体不影响钩子（用同一 Id 重新 Bind 即可更新）。
// handler 或 handler.Func 为 nil 时 panic。
func (h *Hook[T]) Bind(handler *Handler[T]) string {
	if handler == nil || handler.Func == nil {
		panic(errNilHandler)
	}

	h.mu.Lock()
	defer h.mu.Unlock()

	if handler.Id == "" {
		handler.Id = h.generateIdLocked()
	}

	stored := *handler

	if i := h.indexLocked(stored.Id); i >= 0 {
		h.handlers[i] = &stored // replace existing | 替换已有处理器
	} else {
		h.handlers = append(h.handlers, &stored) // append new | 追加新处理器
	}

	// sort handlers by Priority, preserving the original order of equal items
	// 按 Priority 排序处理器，相同项保持原有顺序
	slices.SortStableFunc(h.handlers, func(a, b *Handler[T]) int {
		return cmp.Compare(a.Priority, b.Priority)
	})

	h.publishLocked()

	return stored.Id
}

// BindFunc is similar to Bind but registers a new handler from just the provided function.
//
// The registered handler is added with a default 0 priority and the id will be autogenerated.
//
// If you want to register a handler with custom priority or id use the [Hook.Bind] method.
// BindFunc 与 Bind 类似，但直接从给定函数注册新处理器。注册的处理器默认
// priority 为 0，id 自动生成；需要自定义优先级或 id 请用 [Hook.Bind]。
func (h *Hook[T]) BindFunc(fn func(e T) error) string {
	return h.Bind(&Handler[T]{Func: fn})
}

// Unbind removes one or many hook handler by their id.
// Unbind 按 id 移除一个或多个钩子处理器。
func (h *Hook[T]) Unbind(idsToRemove ...string) {
	if len(idsToRemove) == 0 {
		return
	}

	h.mu.Lock()
	defer h.mu.Unlock()

	before := len(h.handlers)

	h.handlers = slices.DeleteFunc(h.handlers, func(handler *Handler[T]) bool {
		return slices.Contains(idsToRemove, handler.Id)
	})

	if len(h.handlers) != before {
		h.publishLocked()
	}
}

// UnbindAll removes all registered handlers.
// UnbindAll 移除所有已注册的处理器。
func (h *Hook[T]) UnbindAll() {
	h.mu.Lock()
	defer h.mu.Unlock()

	h.handlers = nil

	h.publishLocked()
}

// Length returns to total number of registered hook handlers.
// Length 返回已注册钩子处理器的总数。
func (h *Hook[T]) Length() int {
	if chain := h.chain.Load(); chain != nil {
		return len(*chain)
	}

	return 0
}

// Trigger executes all registered hook handlers one by one
// with the specified event as an argument.
//
// Optionally, this method allows also to register additional one off
// handler funcs that will be temporary appended to the handlers queue.
//
// It returns the error returned by the first handler that fails to
// call event.Next() successfully (aka. the error "bubbles up" the chain).
//
// NB! Each hook handler must call event.Next() in order the hook chain to proceed.
//
// The same event can be passed to Trigger multiple times, even from inside
// a handler of another (or the same) hook: the state of the outer chain is
// restored once the inner Trigger returns. When Trigger returns, the event is
// left as it was before the call, so a late event.Next() (eg. from a
// goroutine that outlived the chain) does nothing.
// Trigger 以指定事件为参数逐个执行所有已注册的钩子处理器。
// 也可额外注册一次性处理函数，临时追加到处理器队列末尾。
// 返回第一个未能成功调用 event.Next() 的处理器产生的错误（即错误沿链条
// "冒泡"）。注意：每个钩子处理器必须调用 event.Next() 钩子链才能继续。
// 同一事件可多次传入 Trigger，甚至在另一个（或同一个）钩子的处理器内部调用：
// 内层 Trigger 返回后恢复外层链条状态。Trigger 返回时事件保持调用前状态，
// 迟到的 event.Next()（如比链条活得久的 goroutine 发起的）不做任何事。
func (h *Hook[T]) Trigger(event T, oneOffHandlerFuncs ...func(T) error) error {
	var fns []func(T) error
	if chain := h.chain.Load(); chain != nil {
		fns = *chain
	}

	if len(oneOffHandlerFuncs) > 0 {
		// allocates a new slice, the shared snapshot is never modified
		// 分配新切片，共享快照绝不被修改
		fns = slices.Concat(fns, oneOffHandlerFuncs)
	}

	if len(fns) == 0 {
		return nil
	}

	// make Trigger re-entrant for the same event
	// 使 Trigger 对同一事件可重入
	prev := event.nextFunc()
	defer event.setNextFunc(prev)

	// A single cursor drives the whole chain: Next runs the handler at the
	// cursor and moves it forward first, so a handler's own e.Next() call
	// continues with the handler after it.
	// 单个游标驱动整个链条：Next 先执行游标处处理器并前移游标，
	// 因此处理器自己的 e.Next() 会继续执行它后面的处理器。
	var cursor int
	event.setNextFunc(func() error {
		if cursor >= len(fns) {
			return nil
		}

		fn := fns[cursor]
		cursor++

		return fn(event)
	})

	return event.Next()
}

// indexLocked returns the position of the handler with the provided id or -1.
// indexLocked 返回指定 id 处理器的位置，不存在则返回 -1。
func (h *Hook[T]) indexLocked(id string) int {
	return slices.IndexFunc(h.handlers, func(handler *Handler[T]) bool {
		return handler.Id == id
	})
}

// generateIdLocked returns an autogenerated id that is not used by
// any of the currently registered handlers (eg. explicitly set to "h1").
// generateIdLocked 返回一个未被当前任何已注册处理器占用的自动生成 id
// （例如被显式设为 "h1" 的情况）。
func (h *Hook[T]) generateIdLocked() string {
	for {
		id := generateHookId()
		if h.indexLocked(id) < 0 {
			return id
		}
	}
}

// publishLocked republishes the immutable snapshot used by Trigger.
// publishLocked 重新发布 Trigger 使用的不可变快照。
func (h *Hook[T]) publishLocked() {
	fns := make([]func(T) error, len(h.handlers))
	for i, handler := range h.handlers {
		fns[i] = handler.Func
	}

	h.chain.Store(&fns)
}

var hookIdSeq atomic.Int64

func generateHookId() string {
	return "h" + strconv.FormatInt(hookIdSeq.Add(1), 36)
}
