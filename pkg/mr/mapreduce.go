// Package mr provides a generic MapReduce with a bounded worker pool, guarded
// channel writes and first-error cancellation. It is modeled on go-zero's core/mr
// so that fan-out/fan-in data processing can be expressed without manual
// goroutine and channel plumbing.
package mr

import (
	"context"
	"errors"
	"fmt"
	"runtime/debug"
	"strings"
	"sync"
	"sync/atomic"
)

const (
	defaultWorkers = 16
	minWorkers     = 1
)

var (
	// ErrCancelWithNil is returned when a mapper/reducer cancels with a nil error.
	ErrCancelWithNil = errors.New("mr: cancelled with nil")
	// ErrReduceNoOutput is returned when the reducer writes no value.
	ErrReduceNoOutput = errors.New("mr: reducer wrote no value")
)

type (
	// ForEachFunc processes an element without producing output.
	ForEachFunc[T any] func(item T)
	// GenerateFunc sends input elements into source.
	GenerateFunc[T any] func(source chan<- T)
	// MapFunc processes an element and writes output to the writer.
	MapFunc[T, U any] func(item T, writer Writer[U])
	// MapperFunc processes an element and writes output, or cancels processing.
	MapperFunc[T, U any] func(item T, writer Writer[U], cancel func(error))
	// ReducerFunc reduces the mapper outputs into a single value, or cancels.
	ReducerFunc[U, V any] func(pipe <-chan U, writer Writer[V], cancel func(error))
	// VoidReducerFunc reduces the mapper outputs without producing a value.
	VoidReducerFunc[U any] func(pipe <-chan U, cancel func(error))
	// Option customizes a MapReduce.
	Option func(opts *mapReduceOptions)

	// Writer is a cancellable sink for active mapper/reducer callbacks.
	// Do not retain a writer or write after its callback has returned.
	Writer[T any] interface {
		Write(v T)
	}

	mapperContext[T, U any] struct {
		execution   *execution
		mapper      MapFunc[T, U]
		source      <-chan T
		collector   chan<- U
		workers     int
		drainSource bool
	}

	mapReduceOptions struct {
		ctx     context.Context
		workers int
	}
)

// WithWorkers sets the number of worker goroutines (minimum 1).
func WithWorkers(workers int) Option {
	return func(opts *mapReduceOptions) {
		if workers < minWorkers {
			opts.workers = minWorkers
		} else {
			opts.workers = workers
		}
	}
}

// WithContext makes scheduling and channel writes honor the given context.
// Callbacks must use ctx themselves for cancellable I/O. Nil means Background.
func WithContext(ctx context.Context) Option {
	return func(opts *mapReduceOptions) { opts.ctx = ctx }
}

// MapReduce maps finite input generated by generate and reduces it to one value.
// Generate must return and must not close source. Cancellation stops scheduling
// and writes; remaining input is drained so a finite generator can finish.
// All started callbacks finish before return. Output order is not guaranteed.
func MapReduce[T, U, V any](generate GenerateFunc[T], mapper MapperFunc[T, U], reducer ReducerFunc[U, V],
	opts ...Option) (V, error) {
	options := buildOptions(opts...)
	if err := context.Cause(options.ctx); err != nil {
		var zero V
		return zero, err
	}
	execution := newExecution(options.ctx)
	defer execution.cancelCause(nil)
	source := buildSource(generate, execution)
	return runMapReduce(source, execution, true, mapper, reducer, options)
}

// MapReduceChan is MapReduce over a caller-owned source channel. The caller
// closes source and cancels its producer. This function does not drain source
// on cancellation, and waits for all started mapper and reducer callbacks.
func MapReduceChan[T, U, V any](source <-chan T, mapper MapperFunc[T, U], reducer ReducerFunc[U, V],
	opts ...Option) (V, error) {
	options := buildOptions(opts...)
	if err := context.Cause(options.ctx); err != nil {
		var zero V
		return zero, err
	}
	execution := newExecution(options.ctx)
	defer execution.cancelCause(nil)
	return runMapReduce(source, execution, false, mapper, reducer, options)
}

// ForEach maps all elements generated by generate with no output.
func ForEach[T any](generate GenerateFunc[T], mapper ForEachFunc[T], opts ...Option) {
	_, _ = MapReduce(generate,
		func(item T, _ Writer[any], _ func(error)) { mapper(item) },
		func(pipe <-chan any, writer Writer[struct{}], _ func(error)) {
			drain(pipe)
			writer.Write(struct{}{})
		}, opts...)
}

// Finish runs fns in parallel, cancelling on the first error.
func Finish(fns ...func() error) error {
	if len(fns) == 0 {
		return nil
	}
	_, err := MapReduce(
		func(source chan<- func() error) {
			for _, fn := range fns {
				source <- fn
			}
		},
		func(fn func() error, _ Writer[any], cancel func(error)) {
			if err := fn(); err != nil {
				cancel(err)
			}
		},
		func(_ <-chan any, _ Writer[any], _ func(error)) {},
		WithWorkers(len(fns)),
	)
	if errors.Is(err, ErrReduceNoOutput) {
		return nil
	}
	return err
}

// FinishVoid runs fns in parallel and ignores errors.
func FinishVoid(fns ...func()) {
	if len(fns) == 0 {
		return
	}
	ForEach(
		func(source chan<- func()) {
			for _, fn := range fns {
				source <- fn
			}
		},
		func(fn func()) { fn() },
		WithWorkers(len(fns)),
	)
}

func buildOptions(opts ...Option) *mapReduceOptions {
	options := &mapReduceOptions{ctx: context.Background(), workers: defaultWorkers}
	for _, opt := range opts {
		opt(options)
	}
	if options.ctx == nil {
		options.ctx = context.Background()
	}
	return options
}

// execution owns cancellation and the first callback panic. Panic reporting is
// buffered so workers can always finish even when the caller is waiting to join.
type execution struct {
	ctx         context.Context
	cancelCause context.CancelCauseFunc
	panicChan   *onceChan
}

func newExecution(parent context.Context) *execution {
	ctx, cancel := context.WithCancelCause(parent)
	return &execution{ctx: ctx, cancelCause: cancel, panicChan: &onceChan{channel: make(chan any, 1)}}
}

func (e *execution) cancel(err error) {
	if err == nil {
		err = ErrCancelWithNil
	}
	e.cancelCause(err)
}

func (e *execution) recoverPanic() {
	if r := recover(); r != nil {
		e.panicChan.write(buildPanicInfo(r))
		e.cancelCause(context.Canceled)
	}
}

func (e *execution) rethrowPanic() {
	select {
	case value := <-e.panicChan.channel:
		panic(value)
	default:
	}
}

func buildSource[T any](generate GenerateFunc[T], execution *execution) chan T {
	source := make(chan T)
	go func() {
		defer close(source)
		defer execution.recoverPanic()
		generate(source)
	}()
	return source
}

func executeMappers[T, U any](mCtx mapperContext[T, U]) {
	var wg sync.WaitGroup
	defer func() {
		if mCtx.drainSource {
			drain(mCtx.source)
		}
		wg.Wait()
		close(mCtx.collector)
	}()

	pool := make(chan struct{}, mCtx.workers)
	writer := newGuardedWriter(mCtx.execution.ctx, mCtx.collector, mCtx.execution.ctx.Done())
	for {
		if mCtx.execution.ctx.Err() != nil {
			return
		}
		select {
		case <-mCtx.execution.ctx.Done():
			return
		case pool <- struct{}{}:
		}
		var item T
		var ok bool
		select {
		case <-mCtx.execution.ctx.Done():
			<-pool
			return
		case item, ok = <-mCtx.source:
			if !ok || mCtx.execution.ctx.Err() != nil {
				<-pool
				return
			}
		}
		wg.Add(1)
		go func() {
			defer wg.Done()
			defer func() { <-pool }()
			defer mCtx.execution.recoverPanic()
			mCtx.mapper(item, writer)
		}()
	}
}

func runMapReduce[T, U, V any](source <-chan T, execution *execution, drainSource bool,
	mapper MapperFunc[T, U], reducer ReducerFunc[U, V], options *mapReduceOptions) (val V, err error) {
	output := make(chan V)
	collector := make(chan U, options.workers)
	writer := newGuardedWriter(execution.ctx, output, execution.ctx.Done())
	var stages sync.WaitGroup
	stages.Go(func() {
		defer close(output)
		defer drain(collector)
		defer execution.recoverPanic()
		reducer(collector, writer, execution.cancel)
	})
	stages.Go(func() {
		executeMappers(mapperContext[T, U]{
			execution: execution,
			mapper: func(item T, w Writer[U]) {
				mapper(item, w, execution.cancel)
			},
			source: source, collector: collector, workers: options.workers, drainSource: drainSource,
		})
	})

	produced := false
	for value := range output {
		if produced {
			execution.panicChan.write("mr: more than one element written in reducer")
			execution.cancelCause(context.Canceled)
			continue
		}
		val, produced = value, true
	}
	stages.Wait()
	execution.rethrowPanic()
	if cause := context.Cause(execution.ctx); cause != nil {
		var zero V
		return zero, cause
	}
	if !produced {
		return val, ErrReduceNoOutput
	}
	return val, nil
}

func buildPanicInfo(r any) string {
	return fmt.Sprintf("%+v\n\n%s", r, strings.TrimSpace(string(debug.Stack())))
}

func drain[T any](channel <-chan T) {
	for range channel {
	}
}

type guardedWriter[T any] struct {
	ctx     context.Context
	channel chan<- T
	done    <-chan struct{}
}

func newGuardedWriter[T any](ctx context.Context, channel chan<- T, done <-chan struct{}) guardedWriter[T] {
	return guardedWriter[T]{ctx: ctx, channel: channel, done: done}
}

func (gw guardedWriter[T]) Write(v T) {
	select {
	case <-gw.ctx.Done():
	case <-gw.done:
	case gw.channel <- v:
	}
}

type onceChan struct {
	channel chan any
	wrote   int32
}

func (oc *onceChan) write(val any) {
	if atomic.CompareAndSwapInt32(&oc.wrote, 0, 1) {
		oc.channel <- val
	}
}
